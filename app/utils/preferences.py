def translate(language: str) -> dict[str, str]:
    """Returns the translation table for a language (Spanish fallback)."""
    table = TRANSLATIONS.get(language)
    if table is None:
        table = TRANSLATIONS[DEFAULT_LANGUAGE]
    merged = dict(TRANSLATIONS[DEFAULT_LANGUAGE])
    merged.update(table)
    return merged