# Defaults applied when a player has no saved configuration yet.
DEFAULT_LANGUAGE = "es"
DEFAULT_CURRENCY = "usd"
DEFAULT_DIFFICULTY = "media"

CURRENCY_SYMBOLS: dict[str, str] = {
    "eur": "€",
    "usd": "$",
    "ars": "ARS$",
}

# ECMAScript locales used to format numbers client-side (toLocaleString).
LOCALES: dict[str, str] = {
    "es": "es-ES",
    "en": "en-US",
    "fr": "fr-FR",
    "de": "de-DE",
    "it": "it-IT",
}

LANGUAGE_CODES = {code for code, _ in LANGUAGES}
CURRENCY_CODES = {code for code, _ in CURRENCIES}
DIFFICULTY_CODES = {code for code, _ in DIFFICULTIES}


def money(amount, currency: str = DEFAULT_CURRENCY) -> str:
    """Formats an amount with the configured currency symbol."""
    symbol = CURRENCY_SYMBOLS.get(currency, CURRENCY_SYMBOLS[DEFAULT_CURRENCY])
    try:
        value = float(amount)
    except (TypeError, ValueError):
        value = 0.0
    return f"{symbol}{value:,.0f}"


